def test_framings():
    t = "a = 1\nb = 2"
    assert C.frame("pkg/x.py", t, "raw") == t
    assert C.frame("pkg/x.py", t, "bare") == "# file: pkg/x.py\na = 1\nb = 2"
    assert C.frame("pkg/x.py", t, "catn") == "     1\ta = 1\n     2\tb = 2\n"
    ch = C.frame("pkg/x.py", t, "chat")
    assert ch.startswith("<|im_start|>user\nHere is `pkg/x.py`:\n```python\n") and "<|im_end|>" in ch
    with pytest.raises(ValueError):
        C.frame("x", t, "nope")


def test_windows_true_history_and_single_scoring():
    key = tiny_key()
    rng = np.random.default_rng(0)
    docs = [rng.integers(3, 500, n) for n in (37, 5, 90, 1, 64)]
    stream = C.pack_stream(docs, EOS)
    assert stream.size == sum(d.size for d in docs) + len(docs)
    full = rows_for(key, stream)
    for W, S in ((16, 16), (16, 12), (32, 7), (stream.size + 5, 3)):
        ws = C.make_windows(stream, W, S, key.context_len, EOS)
        scored = np.concatenate([w.start + 1 + np.flatnonzero(w.labels >= 0) for w in ws])
        assert np.array_equal(np.sort(scored), np.arange(1, stream.size))           # every target exactly once
        for w in ws:
            assert np.array_equal(rows_for(key, w.ids, context=w.context), full[w.start:w.start + w.ids.size])
            ok = w.labels >= 0
            assert np.array_equal(w.labels[ok], stream[w.start + 1 + np.flatnonzero(ok)])
        assert ws[0].context.tolist() == [EOS, EOS]
    # a fresh-segment hash (no context) would differ at a window start inside a document
    w = C.make_windows(stream, 16, 16, key.context_len, EOS)[1]
    assert not np.array_equal(rows_for(key, w.ids)[:2], full[w.start:w.start + 2])
    b = C.batch_windows(C.make_windows(stream, 16, 12, 2, EOS)[-2:], pad_id=0)
    assert b["input_ids"].shape == b["labels"].shape == b["attention_mask"].shape and b["context"].shape[1] == 2


def test_score_mask_restricts_targets():
    stream = np.arange(3, 43)
    mask = np.zeros(40, bool)
    mask[[5, 6, 30]] = True
    ws = C.make_windows(stream, 16, 12, 2, EOS, score_mask=mask)
    scored = sorted(int(w.start + 1 + i) for w in ws for i in np.flatnonzero(w.labels >= 0))
    assert scored == [5, 6, 30]


