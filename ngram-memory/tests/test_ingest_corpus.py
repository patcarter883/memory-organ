GITC = ["-c", "user.name=test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false"]

BODY_A = "".join(f"def func_{i}(x, y):\n    '''Add {i}.'''\n    return x + y * {i}\n\n" for i in range(40))
FAKE_AWS = "AKIA" + "ABCDEFGHIJKLMNOP"   # split so this file itself is not secret-shaped


def _git(repo: Path, *args: str, env=None) -> str:
    return subprocess.run(["git", "-C", str(repo), *GITC, *args], check=True, capture_output=True, text=True,
                          env=env).stdout


def _write(repo: Path, rel: str, data: str | bytes) -> None:
    p = repo / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    (p.write_bytes if isinstance(data, bytes) else p.write_text)(data)


def _commit(repo: Path, msg: str, when: int) -> str:
    import os
    env = dict(os.environ, GIT_AUTHOR_DATE=f"{when} +0000", GIT_COMMITTER_DATE=f"{when} +0000")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", msg, env=env)
    return _git(repo, "rev-parse", "HEAD").strip()


@pytest.fixture(scope="module")
def synth_repo(tmp_path_factory):
    repo = tmp_path_factory.mktemp("synth")
