def test_blob_reader_reads_commit_not_working_tree(synth_repo):
    repo, c1, c2, c3 = synth_repo
    corp = C.load_corpus(repo, c2, C.FileFilter(max_bytes=10_000))
    by = corp.by_path()
    assert corp.commit == c2
    assert by["python/pkg/a.py"].text.endswith("def added_one():\n    return 1\n")
    assert "WORKING TREE" not in by["python/pkg/a.py"].text
    assert "python/pkg/untracked.py" not in by
    assert by["python/pkg/small.py"].text == "z = 3\n"     # c2, not c3
    g = C.GitRepo(repo)
    blobs = g.read_blobs([e.blob for e in g.ls_tree(c2, "python")])
    assert all(isinstance(v, bytes) for v in blobs.values())


def test_filters_secret_scan_and_dedup(synth_repo):
    repo, c1, c2, c3 = synth_repo
    corp = C.load_corpus(repo, c2, C.FileFilter(max_bytes=10_000))
    reasons = dict(corp.excluded)
    assert reasons["python/pkg/notes.md"] == "extension"
    assert reasons["python/pkg/big.py"] == "too_large"
    assert reasons["python/pkg/bin.py"] == "binary"
    assert reasons["python/pkg/gen.py"] == "generated_marker"
    assert reasons["python/vendor/v.py"] == "vendored_or_build_dir"
    assert reasons["python/pkg/secret.py"] == "secret"
    assert reasons["python/pkg/token.py"] == "secret"
    assert "python/pkg/ok_placeholder.py" in corp.by_path()        # placeholder is not a secret
    rules = {(h.path, h.rule) for h in corp.secret_hits}
    assert ("python/pkg/secret.py", "aws_access_key_id") in rules
    assert ("python/pkg/token.py", "generic_secret_assignment") in rules
    assert all(FAKE_AWS not in h.preview for h in corp.secret_hits)   # previews are redacted
    # at c2 a.py gained two lines: a_copy.py is a near (not exact) duplicate of it
    assert corp.dedup.exact_groups == []
    assert ["python/pkg/a.py", "python/pkg/a_copy.py", "python/pkg/b.py"] in corp.dedup.near_clusters
    at_c1 = C.load_corpus(repo, c1, C.FileFilter(max_bytes=10_000))
    assert dict(at_c1.excluded)["python/pkg/a_copy.py"] == "exact_duplicate"
    assert at_c1.dedup.exact_groups == [["python/pkg/a.py", "python/pkg/a_copy.py"]]
    assert ["python/pkg/a.py", "python/pkg/b.py"] in at_c1.dedup.near_clusters
    census = C.load_corpus(repo, c2, C.FileFilter.census_v0())
    assert "python/pkg/big.py" in census.by_path()


