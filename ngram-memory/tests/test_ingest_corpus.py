def test_split_a_rule_and_frozen(synth_repo):
    repo, c1, c2, c3 = synth_repo
    corp = C.load_corpus(repo, c2, C.FileFilter(max_bytes=10_000))
    files = {f.path: f.text for f in corp.files}
    sa = C.assign_split_a(files, corp.commit, test_frac=0.5, dev_frac=0.3, min_chars=10)
    for p, s in sa.assignment().items():
        h = C.split_a_hash(p)
        big = len(files[p]) > 10
        want = "test" if (h < 0.5 and big) else ("dev" if (0.5 <= h < 0.8 and big) else "train")
        assert s == want or s == "neardup_diag"
    # frozen: an existing assignment survives a rule change, a new file gets the rule, a deleted file drops
    files2 = dict(files)
    files2["python/pkg/zz_new.py"] = "q = 1\n" * 10
    del files2["python/pkg/d.py"]
    sa2 = C.assign_split_a(files2, corp.commit, test_frac=0.0, dev_frac=0.0, min_chars=10, frozen=sa)
    a1, a2 = sa.assignment(), sa2.assignment()
    assert all(a2[p] == a1[p] for p in a2 if p in a1)
    assert a2["python/pkg/zz_new.py"] == "train" and "python/pkg/d.py" not in a2
    assert C.SplitA.from_json(sa2.to_json()) == sa2


def test_split_a_cluster_goes_to_train_and_dup_gate():
    base = "".join(f"line_number_{i} = compute_something({i})\n" for i in range(50))
    files = {"python/a.py": base, "python/b.py": base + "extra = 1\n", "python/c.py": "other\n" * 100}
    # force a and b apart: pick fracs so that they land in different splits
    ha, hb = C.split_a_hash("python/a.py"), C.split_a_hash("python/b.py")
    cut = (ha + hb) / 2
    sa = C.assign_split_a(files, test_frac=cut, dev_frac=0.0, min_chars=10,
                          near_clusters=[["python/a.py", "python/b.py"]])
    assert sa.assignment()["python/a.py"] == sa.assignment()["python/b.py"] == "train"
    assert sa.cluster_moves and sa.cluster_moves[0]["to"] == "train"
    # without the cluster, the held-out member is a verbatim duplicate of train -> neardup_diag
    sb = C.assign_split_a(files, test_frac=cut, dev_frac=0.0, min_chars=10)
    held = "python/a.py" if ha < cut else "python/b.py"
    assert sb.assignment()[held] == "neardup_diag" and sb.dup_frac[held] > 0.5


