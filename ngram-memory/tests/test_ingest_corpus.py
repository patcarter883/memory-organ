    _write(repo, "python/pkg/b.py", BODY_A.replace("func_39", "other_39"))        # near duplicate
    _write(repo, "python/pkg/secret.py", f"KEY = '{FAKE_AWS}'\nprint(KEY)\n")
    _write(repo, "python/pkg/token.py", "password = 'Zq8#vL2!pR7@xT4$wN9&'\n")
    _write(repo, "python/pkg/ok_placeholder.py", "api_key = 'your-api-key-goes-here-xxxx'\n")
    _write(repo, "python/pkg/big.py", "x = 1\n" * 3000)                          # 18,000 B
    _write(repo, "python/pkg/bin.py", b"abc\0def\n")
    _write(repo, "python/pkg/gen.py", "# @generated by a tool\nx = 1\n")
    _write(repo, "python/vendor/v.py", "y = 2\n")
    _write(repo, "python/pkg/notes.md", "# notes\n")
    _write(repo, "python/pkg/small.py", "z = 3\n")
    c1 = _commit(repo, "one", 1_700_000_000)
    _write(repo, "python/pkg/a.py", BODY_A + "def added_one():\n    return 1\n")
    _write(repo, "python/pkg/d.py", "def brand_new():\n    return 42\n")
    c2 = _commit(repo, "two", 1_700_000_100)
