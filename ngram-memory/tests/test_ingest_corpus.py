needs_minisgl = pytest.mark.skipif(not (C.MINISGL_REPO / ".git").exists(), reason="minisgl clone absent")


@needs_minisgl
def test_minisgl_frozen_splits_rebuild_identically():
    sa, sb = C.load_split_a(), C.load_split_b()
    if sa is None or sb is None:
        pytest.skip("ingest_splits/*.json not written")
    corp = C.load_corpus(C.MINISGL_REPO, C.MINISGL_HEAD)
    assert len(corp.files) == 250 and sum(f.size for f in corp.files) == 5_414_867 and not corp.secret_hits
    files = {f.path: f.text for f in corp.files}
    again = C.assign_split_a(files, corp.commit, near_clusters=corp.dedup.near_clusters, frozen=sa)
    assert again.to_json() == sa.to_json()
    fresh = C.assign_split_a(files, corp.commit, near_clusters=corp.dedup.near_clusters)
    assert fresh.to_json() == sa.to_json()            # the stored lists are the rule's output at this commit
    assert len(sa.test) == 29 and set(sa.neardup_diag) == {"python/minisgl/mamba2/__init__.py",
                                                            "python/minisgl/models/gemma3.py"}
    d = json.loads(sb.to_json())
    assert (d["n_commits"], d["n_files_with_added_lines"], d["n_added_lines"], len(sb.new_files)) == (110, 52, 4142, 6)


