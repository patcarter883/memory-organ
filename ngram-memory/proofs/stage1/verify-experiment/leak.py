"""Leakage audit: duplicate / near-duplicate files between train and held-out split of ingest.py."""
import glob, os, random, hashlib, json, sys
from pathlib import Path
import numpy as np
from transformers import AutoTokenizer
HOST = "/root/.cache/huggingface/hub/models--Qwen--Qwen2.5-0.5B/snapshots/060db6499f32faf8b98477b0a26969ef7d8b9987"
REPO = "/home/user/patcarter883/minisglang-rdna4/python/minisgl"
EOS = 151643
tok = AutoTokenizer.from_pretrained(HOST)
files = sorted(os.path.relpath(f, REPO) for f in glob.glob(f"{REPO}/**/*.py", recursive=True))
shuf = files[:]; random.Random(0).shuffle(shuf)
n_held = round(0.15 * len(files))
held, train = sorted(shuf[:n_held]), sorted(shuf[n_held:])
R = json.load(open(sys.argv[1]))
assert held == R["data"]["heldout_files"], "split not reproduced"
txt = {f: Path(REPO, f).read_text(errors="replace") for f in files}
h = {f: hashlib.sha1(txt[f].encode()).hexdigest() for f in files}
th = {}
for f in train: th.setdefault(h[f], []).append(f)
print("exact-dup held files:", [(f, th[h[f]]) for f in held if h[f] in th])
print("held sizes (bytes):", {f: len(txt[f]) for f in held})
# symlinks / generated
print("symlinks:", [f for f in files if os.path.islink(Path(REPO, f))])
print("generated-looking:", [f for f in files if any(s in txt[f][:400].lower() for s in ("auto-generated", "autogenerated", "do not edit", "generated by"))])
# token-level 16-gram shingle overlap of held-out files vs ALL train files and vs the 96 used chunks
ids = {f: tok(txt[f], add_special_tokens=False).input_ids for f in files}
K = 16
def sh(a): return {tuple(a[i:i + K]) for i in range(len(a) - K + 1)}
train_sh = set().union(*(sh(ids[f]) for f in train))
# reconstruct train_x exactly like ingest.py
def stream(ps):
    o = []
    for p in ps: o += ids[p] + [EOS]
    return np.asarray(o, dtype=np.int64)
T = 512
tr = stream(train); n = len(tr) // T; tr_all = tr[:n * T].reshape(n, T)
idx = np.sort(np.random.default_rng(0).choice(len(tr_all), size=96, replace=False))
used_sh = set()
for r in tr_all[idx]: used_sh |= sh(r.tolist())
rows = []
for f in held:
    a = ids[f]
    if len(a) < K: rows.append((f, len(a), None, None)); continue
    cov_all = np.zeros(len(a), bool); cov_used = np.zeros(len(a), bool)
    for i in range(len(a) - K + 1):
        s = tuple(a[i:i + K])
        if s in train_sh: cov_all[i:i + K] = True
        if s in used_sh: cov_used[i:i + K] = True
    rows.append((f, len(a), float(cov_all.mean()), float(cov_used.mean())))
rows.sort(key=lambda r: -(r[2] or 0))
tot = sum(r[1] for r in rows)
print(f"held-out tokens covered by a {K}-token span present in: ALL train files = "
      f"{sum(r[1] * (r[2] or 0) for r in rows) / tot:.3f}, the 96 USED train chunks = {sum(r[1] * (r[3] or 0) for r in rows) / tot:.3f}")
for r in rows[:12]: print("  ", r)
# reconstruct held_x and measure covered-by-used fraction on exactly the eval positions
ho = stream(held); n = len(ho) // T; ho_all = ho[:n * T].reshape(n, T)
hidx = np.sort(np.random.default_rng(1).choice(len(ho_all), size=32, replace=False))
cov = np.zeros((32, T), bool)
for b, r in enumerate(ho_all[hidx].tolist()):
    for i in range(T - K + 1):
        if tuple(r[i:i + K]) in used_sh: cov[b, i:i + K] = True
print(f"eval held_x positions inside a {K}-span seen in used train chunks: {cov.mean():.3f}")
np.save("held_cov16.npy", cov)
